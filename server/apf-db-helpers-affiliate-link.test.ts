import { describe, expect, it, vi } from "vitest";
import { upsertAffiliateLink } from "../scripts/apf-db-helpers.mjs";

describe("upsertAffiliateLink", () => {
  it("preserves approved URL/status when a generated write arrives", async () => {
    const query = vi.fn(async () => [{ affectedRows: 1 }]);
    await upsertAffiliateLink(
      { query },
      {
        productId: 42,
        affiliateNickname: "UnlovedProducts",
        platformProductId: "123456",
        affiliateUrl: "https://www.checkout-ds24.com/redir/123456/UnlovedProducts/apf_123456",
        campaignKey: "apf_123456",
        status: "generated",
        notes: "Generated by APF Digistore24 importer",
      },
    );

    expect(query).toHaveBeenCalledTimes(1);
    const sql = String(query.mock.calls[0][0]);
    expect(sql).toMatch(/status='approved'\s+AND VALUES\(status\) <> 'approved'/);
    expect(sql).toMatch(/affiliate_url=IF\(/);
    expect(sql).toMatch(/status=IF\(/);
    expect(sql).toMatch(/notes=IF\(/);
  });

  it("still allows an approved write to replace URL/status/notes", async () => {
    const query = vi.fn(async () => [{ affectedRows: 1 }]);
    await upsertAffiliateLink(
      { query },
      {
        productId: 42,
        affiliateNickname: "UnlovedProducts",
        platformProductId: "123456",
        affiliateUrl: "https://www.checkout-ds24.com/redir/123456/UnlovedProducts/promo_real",
        status: "approved",
        notes: "Collected affiliate/promolink",
      },
    );

    const params = query.mock.calls[0][1] as unknown[];
    expect(params).toContain("approved");
    expect(params).toContain(
      "https://www.checkout-ds24.com/redir/123456/UnlovedProducts/promo_real",
    );
  });
});
